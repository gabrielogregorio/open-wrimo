export const RARE_ODDS = 20;

export type Twist = { twist: string; rare: boolean };

// The first draw decides whether this roll is a rare one; only the top 1/RARE_ODDS of it is.
export const rollTwist = (random: Random, previous?: string): Twist => {
  const rare = random() >= 1 - 1 / RARE_ODDS;

  return { twist: pickOther(rare ? RARE_TWISTS : TWISTS, previous, random), rare };
};

// The die shows a face from 1 to 6 together with the twist.
export const rollFace = (random: Random): number => Math.min(6, Math.floor(random() * 6) + 1);
