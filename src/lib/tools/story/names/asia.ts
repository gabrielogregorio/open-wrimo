// Sources checked:
// - Behind the Name, usage lists (https://www.behindthename.com/names/usage/japanese, /chinese,
//   /korean, /thai, /indonesian, /filipino, /tagalog).
// - Japan: The Tale of Genji and Heian court diaries (Murasaki Shikibu, Sei Shonagon), Kokin Wakashu
//   poet lists, Heike Monogatari; Edo records and kabuki/ukiyo-e names; Meiji Yasuda Life yearly
//   name rankings (https://www.meijiyasuda.co.jp/enjoy/ranking/), Taisho and early Showa lists.
// - China: figures of the Tang, Song, Ming and Qing dynastic histories, Tang poets, Dream of the Red
//   Chamber, Water Margin, Tang chuanqi tales; Republic-era public figures; Wikipedia "Lists of
//   most common surnames in Asian countries".
// - Korea: Annals of the Joseon Dynasty figures, Chunhyangjeon, Heungbujeon, Hong Gildong jeon,
//   gisaeng and household-register names; South Korean Statistics/court naming studies of the
//   1950s-1980s (most popular names per decade as reported by Korean press).
// - Philippines: Claveria "Catalogo alfabetico de apellidos" (1849); Philippine Statistics Authority
//   popular baby names.
// - Precolonial Philippines (given names only from these pages, opened when the list was curated):
//   Wikipedia "Laguna Copperplate Inscription" (Postma's translation: Angkatan, Namwaran, Jayadewa,
//   Ganashakti, Bisruta), "Rajah Humabon" (Pigafetta-era Cebu, Butuan, Madja-as, Tondo, Maynila,
//   Namayan and Maguindanao rulers), "Lakandula", "Maragtas", "Hinilawod", "Biag ni Lam-ang",
//   "Hudhud ni Aliguyon". Women are few: one inscription, one genealogy and the epics. Humamay
//   (called fabricated by linguists), Urduja (legend placed outside the islands), deities and
//   Tagalog vocabulary words are left out.
// - Indonesia: Pararaton, Nagarakretagama (Prapanca, 1365), Kidung Sunda, Old Javanese kakawin;
//   present-day name usage (Behind the Name, Indonesian press).
// - Majapahit women (opened when the list was curated): Wikipedia "Rajasa dynasty", "Majapahit",
//   "Hayam Wuruk" (royal women of the Singhasari and Majapahit courts), "Damarwulan" and
//   "Panji (prince)" (heroines of the Majapahit-era cycles). Generic words and wayang heroines of
//   the Indian epics are left out.
// - Thailand: Surname Act 1913; Behind the Name Thai list; common Thai surnames (Wikipedia, Forebears).
// - Ayutthaya (opened when the list was curated): Wikipedia "List of Thai royal consorts" (titles
//   such as Thewi stripped), "List of Thai monarchs" (regnal and personal names), "Ayutthaya
//   Kingdom", "Khun Chang Khun Phaen", "Bang Rachan" (spelled here in RTGS). Unattested one-word
//   commoner names are left out.
//
// Women of the past were recorded far less than men. Where the record is thin (Heian, Joseon), the
// female lists add names from literature, legend and court titles used as names. The precolonial
// Philippine, Majapahit and Ayutthaya lists hold only attested names and are shorter.
